// Compile app/carbon.scss → app/carbon.css once (Carbon is huge; compiling it
// through Next on every change made dev rebuilds crawl). Re-run after
// changing carbon.scss or upgrading @carbon/react:  pnpm --filter orch-web build:carbon-css
import * as sass from 'sass'
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const entry = path.join(here, '..', 'app', 'carbon.scss')
const out = path.join(here, '..', 'app', 'carbon.css')

// Resolve "@scope/pkg/rest" or "pkg/rest" relative to the importing file,
// so pnpm's nested node_modules layout works.
const importer = {
  findFileUrl(url, context) {
    if (url.startsWith('.') || url.startsWith('/') || url.includes(':')) return null
    const parts = url.split('/')
    const pkg = url.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]
    const rest = parts.slice(url.startsWith('@') ? 2 : 1).join('/')
    const from = context?.containingUrl ? fileURLToPath(context.containingUrl) : entry
    try {
      const pkgJson = createRequire(from).resolve(`${pkg}/package.json`)
      return pathToFileURL(path.join(path.dirname(pkgJson), rest))
    } catch {
      return null
    }
  },
}

const result = sass.compile(entry, {
  style: 'compressed',
  importers: [importer],
  quietDeps: true,
  silenceDeprecations: ['import', 'global-builtin', 'mixed-decls', 'color-functions', 'slash-div'],
  logger: sass.Logger.silent,
})
writeFileSync(out, `/* Generated by scripts/build-carbon-css.mjs from app/carbon.scss — do not edit. */\n${result.css}\n`)
console.log(`wrote ${path.relative(process.cwd(), out)} (${(result.css.length / 1024).toFixed(0)} KB)`)
